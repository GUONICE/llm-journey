# -*- coding: utf-8 -*-


def safe_get(data, key, default=None):
    # try 块：把「可能会出错的代码」包起来
    try:
        # 用中括号直接取值 —— 这正是平时会崩溃的写法
        # 如果 data 不是字典，或者 key 不存在，这一行就会抛异常
        return data[key]

    # 同时捕获三种可能的错误，写成元组
    #   TypeError  → data 根本不是字典（比如字符串、数字、None）
    #   KeyError   → data 是字典，但 key 不存在
    #   IndexError → data 是列表，但下标越界
    except (TypeError, KeyError, IndexError):
        # 出了上面任何一种错误，都不让程序崩，返回默认值
        return default


# ---------------------------------------------------------------
# 测试 1：正常取值，key 存在
# ---------------------------------------------------------------
# 期望返回 1
result1 = safe_get({"a": 1}, "a")
print("测试1 正常取值:", result1)

# ---------------------------------------------------------------
# 测试 2：key 不存在，不传默认值
# ---------------------------------------------------------------
# 触发 KeyError，default 用默认值 None，所以返回 None
result2 = safe_get({"a": 1}, "b")
print("测试2 key不存在:", result2)

# ---------------------------------------------------------------
# 测试 3：data 根本不是字典
# ---------------------------------------------------------------
# 字符串 "不是字典" 用 ["a"] 取值会触发 TypeError
# 不加 try 的话程序会直接崩，加了就返回 None
result3 = safe_get("不是字典", "a")
print("测试3 data非字典:", result3)

# ---------------------------------------------------------------
# 测试 4：key 不存在，但传了自定义默认值
# ---------------------------------------------------------------
# 触发 KeyError，返回我们指定的 "默认值"
result4 = safe_get({"a": 1}, "b", "默认值")
print("测试4 自定义默认值:", result4)

# ---------------------------------------------------------------
# 测试 5：嵌套取值，验证通用性
# ---------------------------------------------------------------
# 模拟 API 返回的数据，usage 字段存在
api_response = {"content": "你好", "usage": {"total_tokens": 37}}

# 取出内层字典，再取里面的 total_tokens
usage = safe_get(api_response, "usage", {})
tokens = safe_get(usage, "total_tokens", 0)
print("测试5 嵌套取值:", tokens)

# ---------------------------------------------------------------
# 测试 6：空的 API 返回（流式输出场景）
# ---------------------------------------------------------------
# 流式返回时没有 usage 字段，验证不会崩
stream_response = {"content": "你好"}

usage2 = safe_get(stream_response, "usage", {})
tokens2 = safe_get(usage2, "total_tokens", 0)
print("测试6 流式无usage:", tokens2)
